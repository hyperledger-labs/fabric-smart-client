package main

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/hyperledger-labs/fabric-smart-client/pkg/utils/errors"
)

// mergifyFile is the Mergify configuration, relative to the repository root.
const mergifyFile = ".mergify.yml"

// firstBranched is the first minor that can get a release branch: older ones were cut before
// patch releases existed.
var firstBranched = semver{Minor: 29}

// mergifyHeader opens the generated Mergify configuration.
const mergifyHeader = `# Generated by scripts/release mergify with the release of a minor; do not edit: release
# check fails on any change. docs/dev/releasing.md, Backports, describes the process.
#
# Mergify backports a fix merged to main onto a release branch when the PR has the
# label backport/X.Y: it cherry-picks the squash commit onto release-X.Y and opens a
# PR titled "<title> (backport #N)", assigned to the original author. A conflict is
# committed as such, and the PR is labelled "conflicts". Mergify never merges the PR.
# Mergify cannot derive the branch from the label, so each supported minor has a rule.
`

// supportedMinors returns the minors that take backports, highest first: the two highest
// minors from firstBranched on with a release data file in dir.
func supportedMinors(dir string) ([]semver, error) {
	files, err := filepath.Glob(filepath.Join(dir, filepath.FromSlash(releasesDir), "v*.0.json"))
	if err != nil {
		return nil, errors.Wrap(err, "failed listing the release data files")
	}
	var minors []semver
	for _, f := range files {
		v, ok := parseVersion(strings.TrimSuffix(filepath.Base(f), ".json"))
		if ok && v.Patch == 0 && v.compare(firstBranched) >= 0 {
			minors = append(minors, v)
		}
	}
	slices.SortFunc(minors, func(a, b semver) int { return b.compare(a) })
	return minors[:min(len(minors), 2)], nil
}

// mergify returns the Mergify configuration of the tree in dir: a backport rule for the
// release branch of each supported minor. A rule may exist before its branch, which is created
// when the first fix needs a backport.
func mergify(dir string) (string, error) {
	minors, err := supportedMinors(dir)
	if err != nil {
		return "", err
	}
	if len(minors) == 0 {
		return mergifyHeader + "pull_request_rules: []\n", nil
	}
	var b strings.Builder
	b.WriteString(mergifyHeader + "pull_request_rules:\n")
	for _, v := range minors {
		fmt.Fprintf(&b, `  - name: backport to release-%[1]d.%[2]d
    conditions:
      - base=main
      - label=backport/%[1]d.%[2]d
    actions:
      backport:
        branches: [release-%[1]d.%[2]d]
        assignees: ["{{ author }}"]
`, v.Major, v.Minor)
	}
	return b.String(), nil
}

// checkMergify fails when the Mergify configuration in dir is not what mergify generates.
func checkMergify(dir string) error {
	got, err := os.ReadFile(filepath.Join(dir, mergifyFile))
	if err != nil {
		return errors.Wrapf(err, "failed reading %s", mergifyFile)
	}
	want, err := mergify(dir)
	if err != nil {
		return err
	}
	if string(got) != want {
		return errors.Errorf(`%s is not what "mergify" generates from the release data: it was edited, `+
			`or a minor's release data came without its rule; regenerate it with `+
			`go run ./scripts/release mergify > %s`, mergifyFile, mergifyFile)
	}
	return nil
}
