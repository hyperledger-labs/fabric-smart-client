package view

import (
	"context"
	"fmt"

	"github.com/hyperledger-labs/fabric-smart-client/pkg/utils/errors"
)

const (
	OK    = 200
	ERROR = 500
)

type Message struct {
	SessionID    string // Session Identifier
	ContextID    string // Context Identifier
	Caller       string // View Identifier of the caller
	FromEndpoint string // Endpoint identifier of the caller
	FromPKID     []byte // PK identifier of the caller
	Status       int32  // Message Status (OK, ERROR)
	Payload      []byte // Payload
	Ctx          context.Context
	// Protocol is the stable protocol name "<component>/<name>" the session's initiator states,
	// empty if its view declares none or the message comes from a responder.
	Protocol string
	// Versions is the encoded version of each component's formats the session's initiator chose
	// for it, stated on every message the initiator sends; nil on a responder's messages. The
	// comm layer decodes it when the message creates a responder session.
	Versions []byte
}

func (m *Message) String() string {
	return fmt.Sprintf("[session:%s,context:%s,caller:%s,endpoint:%s",
		m.SessionID,
		m.ContextID,
		m.Caller,
		m.FromEndpoint)
}

// SessionInfo contains information about a session and the remote peer.
type SessionInfo struct {
	// ID is the unique identifier for the logical session.
	// It is generated by the initiator and used to multiplex messages.
	ID string
	// Caller is the authenticated identity of the remote peer.
	// The communication layer guarantees that this identity matches the
	// public key used in the underlying secure transport (e.g., TLS certificate).
	Caller Identity
	// CallerViewID is the string identifier of the View that initiated
	// the session on the remote peer's side.
	CallerViewID string
	// RemoteEndpoint is the network address (e.g., IP:port) of the remote peer.
	RemoteEndpoint string
	// RemotePKID is the cryptographically verified public key identifier
	// (hash) of the remote peer. The communication layer ensures that
	// this ID is bound to the verified transport-layer identity.
	RemotePKID []byte
	// LocalPKID is the public key identifier of the local node, i.e. the
	// identifier of the key-pair that instantiated the local communication
	// stack. It is the local-side counterpart of RemotePKID and lets a session
	// consumer select the material (e.g. its signer) bound to its own identity
	// directly from the session, symmetrically to how RemotePKID identifies
	// the remote peer.
	LocalPKID []byte
	// Closed is true if the session has been closed.
	Closed bool
}

func (i *SessionInfo) String() string {
	return fmt.Sprintf("session info [%s,%s,%s,%s,%s,%v]", i.ID, i.Caller, i.CallerViewID, i.RemoteEndpoint, i.RemotePKID, i.Closed)
}

// Session encapsulates a communication channel to an endpoint
type Session interface {
	Info() SessionInfo

	// Send sends the payload to the endpoint with the passed context.
	Send(ctx context.Context, payload []byte) error

	// SendError sends an error to the endpoint with the passed payload and context.
	SendError(ctx context.Context, payload []byte) error

	// Receive returns a channel of messages received from the endpoint
	Receive() <-chan *Message

	// Close releases all the resources allocated by this session
	Close()
}

// VersionedSession is implemented by a session that knows which version of each component's
// formats it uses; FSC's sessions over the network do. The initiator chose the versions from
// both nodes' ranges, the highest both support, and states them on each message it sends.
// A caller finds the interface by type assertion, or calls SessionVersion.
type VersionedSession interface {
	// Version returns the version of the named component's formats the session uses. ok is
	// false if the node does not have the component. On a session this node opened, the first
	// call negotiates the versions, which may open the stream to the peer, bounded by ctx; the
	// result holds for the session's lifetime and every message states it. It fails with an
	// error wrapping ErrNoCommonVersion if the peer supports no version this node does.
	Version(ctx context.Context, component string) (version uint32, ok bool, err error)
}

// ErrNoCommonVersion is wrapped by VersionedSession.Version when the two nodes support no common
// version of a component.
var ErrNoCommonVersion = errors.New("no common version")

// SessionVersion returns the version of the named component's formats that s uses; see
// VersionedSession. A session that does not implement VersionedSession, such as an in-process
// session or an application's wrapper, uses version 1, as does one whose node does not have the
// component.
func SessionVersion(ctx context.Context, s Session, component string) (uint32, error) {
	vs, ok := s.(VersionedSession)
	if !ok {
		return 1, nil
	}
	v, ok, err := vs.Version(ctx, component)
	if err != nil || !ok {
		return 1, err
	}
	return v, nil
}
