const curvesRoot = "./testdata/curves"

// curveIDForDir derives the idemixgen curve identifier (e.g. "BLS12_381_BBS") from a
// fixture directory produced by testdata/curves/generate.sh, of the form
// testdata/curves/<scheme>/<CURVE>[/admin]. fabricmsp.GetLocalMspConfigWithType never
// populates IdemixMSPConfig.CurveId itself (idemixgen does not persist the curve name in
// any of the on-disk fixture files), so tests must set it explicitly to exercise anything
// beyond each scheme's default curve.
func curveIDForDir(dir string) string {
	parts := strings.Split(filepath.ToSlash(dir), "/")
	for i, part := range parts {
		if part == "admin" && i > 0 {
			return parts[i-1]
		}
	}
	return parts[len(parts)-1]
}

// curveDirs returns, for every scheme (dlog, aries) and curve fixture generated by
// testdata/curves/generate.sh, the directory containing that curve's member MSP
// configuration (msp/, user/) and admin identity (admin/msp/, admin/user/), so tests can
// exercise every supported curve/scheme combination.
func curveDirs(t *testing.T) []string {
	t.Helper()

	schemes, err := os.ReadDir(curvesRoot)
	require.NoError(t, err)

	var dirs []string
	for _, scheme := range schemes {
		if !scheme.IsDir() {
			continue
		}
		schemeDir := filepath.Join(curvesRoot, scheme.Name())
		curves, err := os.ReadDir(schemeDir)
		require.NoError(t, err)
		for _, curve := range curves {
			if !curve.IsDir() {
				continue
			}
			dirs = append(dirs, filepath.Join(schemeDir, curve.Name()))
		}
	}
	sort.Strings(dirs)
	require.NotEmpty(t, dirs, "no curve fixtures found under %s", curvesRoot)

	return dirs
}

